-- ============================================================================
-- FisioClin — Domínio Principal (V1)
-- Fonte de verdade deste módulo. Migração aditiva: sem DROP/rollback via reexecução.
-- Convenções: <entidade>_id identity; enumerados <entidade>_tipo / <entidade>_situacao
-- (nunca "status"); constraints nomeadas ck_/uk_/fk_/idx_; FKs restritivas por padrão.
-- ============================================================================

-- Cadastro de Planos de Saúde / Convênios
CREATE TABLE fisio.convenio (
    convenio_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cnpj        VARCHAR(14) NOT NULL,
    nome        VARCHAR(100) NOT NULL,
    CONSTRAINT uk_convenio_cnpj UNIQUE (cnpj)
);

-- Cadastro de Fisioterapeutas / Terapeutas / Instrutores
CREATE TABLE fisio.profissional (
    profissional_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cpf             VARCHAR(11) NOT NULL,
    nome            VARCHAR(100) NOT NULL,
    dt_nascimento   DATE NOT NULL,
    email           VARCHAR(100),
    telefone        VARCHAR(15) NOT NULL,
    registro_numero VARCHAR(20) NOT NULL,   -- ex.: CREFITO 12345-F
    registro_orgao  VARCHAR(100) NOT NULL,  -- ex.: CREFITO-3
    login           VARCHAR(50),            -- vínculo com o usuário autenticado (opcional; admin não tem)
    CONSTRAINT uk_profissional_cpf UNIQUE (cpf),
    CONSTRAINT uk_profissional_registro UNIQUE (registro_orgao, registro_numero),
    CONSTRAINT uk_profissional_login UNIQUE (login)
);

-- Tabela Única de Modalidades / Serviços Prestados
CREATE TABLE fisio.modalidade (
    modalidade_id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome                   VARCHAR(50) NOT NULL, -- Ex: 'Fisioterapia', 'Pilates', 'RPG', 'Massagem', 'Liberação'
    duracao_minutos        INT NOT NULL DEFAULT 50,
    valor_base             DECIMAL(10,2) NOT NULL,
    capacidade_simultanea  INT NOT NULL DEFAULT 1, -- fisio/RPG: 1 (individual); pilates: até 4
    CONSTRAINT uk_modalidade_nome UNIQUE (nome),
    CONSTRAINT ck_modalidade_capacidade CHECK (capacidade_simultanea >= 1)
);

-- Cadastro Unificado de Clientes/Pacientes
CREATE TABLE fisio.cliente (
    cliente_id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cpf                VARCHAR(11), -- nullable: criança pode não ter CPF
    nome               VARCHAR(100) NOT NULL,
    dt_nascimento      DATE NOT NULL,
    email              VARCHAR(100),
    telefone           VARCHAR(15),
    convenio_id        INT REFERENCES fisio.convenio(convenio_id), -- restritiva (sem cascade)
    convenio_numero    VARCHAR(50), -- número do plano, quando convênio
    cliente_situacao   VARCHAR(20) NOT NULL DEFAULT 'ATIVO'
        CONSTRAINT ck_cliente_situacao CHECK (cliente_situacao IN ('ATIVO', 'INATIVO'))
);

-- CPF único quando informado (Postgres: índice único parcial; H2: garantir na aplicação)
CREATE INDEX idx_cliente_nome ON fisio.cliente (nome);

-- Central Única de Sessões (Agenda, Atendimento e Fluxo Operacional)
CREATE TABLE fisio.sessao (
    sessao_id            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id           INT NOT NULL REFERENCES fisio.cliente(cliente_id),
    profissional_id      INT NOT NULL REFERENCES fisio.profissional(profissional_id),
    modalidade_id        INT NOT NULL REFERENCES fisio.modalidade(modalidade_id),
    data_hora_inicio     TIMESTAMP NOT NULL,
    data_hora_fim        TIMESTAMP NOT NULL,
    sessao_tipo          VARCHAR(25) NOT NULL
        CONSTRAINT ck_sessao_tipo CHECK (sessao_tipo IN ('AVALIACAO', 'TRATAMENTO', 'REAVALIACAO')),
    pagamento_origem     VARCHAR(20) NOT NULL
        CONSTRAINT ck_sessao_pagamento_origem CHECK (pagamento_origem IN ('PARTICULAR', 'CONVENIO')),
    sessao_situacao      VARCHAR(20) NOT NULL DEFAULT 'AGENDADA'
        CONSTRAINT ck_sessao_situacao CHECK (sessao_situacao IN
            ('AGENDADA', 'CONFIRMADA', 'EM_ANDAMENTO', 'REALIZADA', 'FALTOU', 'CANCELADA')),
    observacoes_recepcao TEXT,
    CONSTRAINT ck_sessao_periodo CHECK (data_hora_fim > data_hora_inicio)
);

CREATE INDEX idx_sessao_prof_agenda ON fisio.sessao (profissional_id, data_hora_inicio);
CREATE INDEX idx_sessao_cliente     ON fisio.sessao (cliente_id);

-- Prontuário / Registro Clínico (um registro por paciente da sessão:
-- sessão de grupo, ex. pilates com até 4 pacientes simultâneos)
CREATE TABLE fisio.sessao_prontuario (
    prontuario_id        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sessao_id            INT NOT NULL UNIQUE REFERENCES fisio.sessao(sessao_id) ON DELETE CASCADE,
    data_registro        TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    queixa_subjetiva     TEXT, -- Relato do cliente (escala de dor, sintomas)
    avaliacao_objetiva   TEXT, -- Testes físicos e palpação (crucial em AVALIACAO/REAVALIACAO)
    conduta_procedimento TEXT, -- O que foi executado (exercícios, manipulações)
    plano_orientacoes    TEXT  -- Recomendações para casa ou próximos passos
    -- 1:1 com sessao: o paciente é o cliente_id do agendamento; atendimento
    -- individualizado em ambiente compartilhado — o "grupo" existe na agenda
    -- (N sessões no mesmo slot, limitadas por modalidade.capacidade_simultanea)
);
