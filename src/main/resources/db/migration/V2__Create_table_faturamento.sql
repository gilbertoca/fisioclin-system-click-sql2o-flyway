-- Como o fluxo funciona na prática (sem complicação)
-- Consulta avulsa (Particular). A recepção gera 1 faturamento (CONSOLIDADO), 1 faturamento_item apontando para a sessao_id e 1 recebimento_parcela já marcada como PAGO via PIX.
-- Pacote fechado antecipado (10 sessões). Você cria o faturamento com as parcelas do cartão e vai vinculando os faturamento_item conforme as sessões vão sendo criadas ou 
-- realizadas (ou já cria as 10 sessões agendadas na hora da venda).
-- Repasse para profissionais (comissão). Como cada faturamento_item aponta para a sessao_id, e a sessao tem profissional_id e sessao_situacao, você consegue calcular com 
-- exatidão quanto cada médico ou fisioterapeuta produziu no mês usando apenas sessões REALIZADA e pagas.
-- Cabeçalho do Faturamento (Conta/Fatura do Cliente ou Lote de Convênio)
CREATE TABLE fisio.faturamento (
    faturamento_id       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id           INT REFERENCES fisio.cliente(cliente_id), -- nullable se for lote de convênio
    pagamento_origem     VARCHAR(20) NOT NULL
        CONSTRAINT ck_faturamento_origem CHECK (pagamento_origem IN ('PARTICULAR', 'CONVENIO')),
    convenio_id          INT REFERENCES fisio.convenio(convenio_id),
    valor_bruto          DECIMAL(10,2) NOT NULL,
    valor_desconto       DECIMAL(10,2) NOT NULL DEFAULT 0.00,
    valor_liquido        DECIMAL(10,2) NOT NULL,
    data_emissao         TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    faturamento_situacao VARCHAR(20) NOT NULL DEFAULT 'ABERTO'
        CONSTRAINT ck_faturamento_situacao CHECK (faturamento_situacao IN ('ABERTO', 'CONSOLIDADO', 'CANCELADO')),
    observacoes          TEXT,
    CONSTRAINT ck_faturamento_particular_cliente CHECK (
        (pagamento_origem = 'PARTICULAR' AND cliente_id IS NOT NULL) OR
        (pagamento_origem = 'CONVENIO' AND convenio_id IS NOT NULL)
    )
);

-- Itens do Faturamento (Sessões vinculadas à fatura)
CREATE TABLE fisio.faturamento_item (
    faturamento_item_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    faturamento_id      INT NOT NULL REFERENCES fisio.faturamento(faturamento_id),
    sessao_id           INT NOT NULL REFERENCES fisio.sessao(sessao_id),
    valor_item          DECIMAL(10,2) NOT NULL,
    CONSTRAINT uk_faturamento_item_sessao UNIQUE (sessao_id)
);

-- Parcelas de Recebimento (Fluxo de Caixa)
CREATE TABLE fisio.recebimento_parcela (
    parcela_id       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    faturamento_id   INT NOT NULL REFERENCES fisio.faturamento(faturamento_id),
    numero_parcela   INT NOT NULL DEFAULT 1,
    valor_parcela    DECIMAL(10,2) NOT NULL,
    data_vencimento  DATE NOT NULL,
    parcela_situacao VARCHAR(20) NOT NULL DEFAULT 'PENDENTE'
        CONSTRAINT ck_parcela_situacao CHECK (parcela_situacao IN ('PENDENTE', 'PAGO', 'GLOSADO', 'CANCELADO')),
    data_pagamento   TIMESTAMP,
    pagamento_meio   VARCHAR(30)
        CONSTRAINT ck_parcela_meio CHECK (pagamento_meio IN ('DINHEIRO', 'CARTAO_CREDITO', 'CARTAO_DEBITO', 'PIX', 'TRANSFERENCIA', 'FATURA_CONVENIO')),
    CONSTRAINT uk_faturamento_numero_parcela UNIQUE (faturamento_id, numero_parcela)
);
